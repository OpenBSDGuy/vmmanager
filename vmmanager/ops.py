"""VM operations: create, update, delete, start, run, connect, stop and disk safety checks."""

import os
import pwd
import re
import shutil
import stat
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from vmmanager import __version__, confblock, tomlio, vmctl
from vmmanager.errors import VmmError
from vmmanager.inventory import VmEntry
from vmmanager.layout import Layout, quote, validate_name
from vmmanager.rootwrite import RootTransaction
from vmmanager.system import System

_DISK_SIZE = re.compile(r"\d+[KMGTkmgt]?")


@dataclass
class VmSpec:
    name: str
    memory: str = "1G"
    cpus: int = 1
    disk_size: str = "20G"
    iso: str | None = None
    internet: bool = True
    os_label: str = ""
    notes: str = ""


def vm_conf_check(sys: System, layout: Layout) -> str | None:
    return vmctl.check_config(sys, layout.vm_conf)


def require_clean_config(sys: System, layout: Layout) -> None:
    problem = vm_conf_check(sys, layout)
    if problem is not None:
        raise VmmError("vm.conf already has errors; fix them first", detail=problem)


def aggregate_text(layout: Layout, extra: Path | None = None, exclude: Path | None = None) -> str:
    """Include lines for every managed conf; extra/exclude reflect files staged but not yet on disk."""
    paths = set(layout.etc_dir.glob("*/*.conf"))
    if extra is not None:
        paths.add(extra)
    paths.discard(exclude)
    lines = ["# generated by vmmanager — do not edit"] + [f'include "{p}"' for p in sorted(paths)]
    return "\n".join(lines) + "\n"


def with_include(vm_conf_text: str, layout: Layout) -> str:
    if any(line.strip() == layout.include_line for line in vm_conf_text.splitlines()):
        return vm_conf_text
    return vm_conf_text + "\n# added by vmmanager\n" + layout.include_line + "\n"


def _tx(sys: System, layout: Layout) -> RootTransaction:
    return RootTransaction(sys, lambda: vm_conf_check(sys, layout))


def _require_stopped(sys: System, name: str) -> None:
    for st in vmctl.status(sys):
        if st.name == name and st.state != "stopped":
            raise VmmError(f"VM '{name}' is {st.state}; stop it first")


def create_vm(sys: System, layout: Layout, spec: VmSpec) -> None:
    validate_name(spec.name)
    if spec.iso is not None:
        quote(spec.iso)
    if not _DISK_SIZE.fullmatch(spec.disk_size):
        raise VmmError(f"Invalid disk size {spec.disk_size!r}: use a size like 20G")
    conf_path = layout.system_conf(spec.name)
    block = confblock.render_block(
        spec.name, memory=spec.memory, cpus=spec.cpus, disk=layout.disk(spec.name),
        cdrom=spec.iso, internet=spec.internet, owner=layout.user,
    )
    require_clean_config(sys, layout)
    taken = {s.name: s.owner_user for s in vmctl.status(sys)}
    taken.update({p.stem: p.parent.name for p in layout.etc_dir.glob(f"*/{spec.name}.conf")})
    if spec.name in taken:
        raise VmmError(f"name '{spec.name}' is already used by {taken[spec.name]}")
    vm_dir = layout.vm_dir(spec.name)
    if vm_dir.exists():
        raise VmmError(f"folder {vm_dir} already exists — delete or rename it first")

    vm_dir.mkdir(parents=True)
    try:
        vmctl.create_disk(sys, layout.disk(spec.name), spec.disk_size)
        tomlio.save(layout.extras(spec.name), {
            "iso": spec.iso or "", "os": spec.os_label, "notes": spec.notes,
            "created": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "version": __version__,
        })
        tx = _tx(sys, layout)
        tx.write(conf_path, block)
        tx.write(layout.aggregate, aggregate_text(layout, extra=conf_path))
        tx.write(layout.vm_conf, with_include(sys.read_file(layout.vm_conf) or "", layout))
        tx.commit()
    except BaseException:  # incl. Ctrl-C; RootTransaction already restored /etc, so the folder is orphaned
        shutil.rmtree(vm_dir, ignore_errors=True)
        raise
    # /etc now references the disk: on reload failure keep everything
    try:
        vmctl.reload(sys)
    except Exception as e:
        detail = e.detail if isinstance(e, VmmError) else str(e)
        raise VmmError(f"{spec.name} was created but vmd could not reload its configuration",
                       detail=f"{detail}\nRun: doas vmctl reload") from e


def _own_conf(layout: Layout, name: str) -> Path:
    path = layout.system_conf(name)
    if not path.is_file():
        raise VmmError(f"VM '{name}' has no vmmanager config")
    return path


def update_vm(sys: System, layout: Layout, name: str, changes: dict[str, object]) -> None:
    validate_name(name)
    path = _own_conf(layout, name)
    require_clean_config(sys, layout)
    _require_stopped(sys, name)
    tx = _tx(sys, layout)
    tx.write(path, confblock.edit_block(sys.read_file(path) or "", changes))
    tx.commit()
    if "cdrom" in changes:
        extras = tomlio.load(layout.extras(name))
        extras["iso"] = changes["cdrom"] or ""
        tomlio.save(layout.extras(name), extras)
    vmctl.reload(sys)


def delete_vm(sys: System, layout: Layout, name: str) -> None:
    validate_name(name)
    path = _own_conf(layout, name)
    require_clean_config(sys, layout)
    _require_stopped(sys, name)
    tx = _tx(sys, layout)
    tx.delete(path)
    tx.write(layout.aggregate, aggregate_text(layout, exclude=path))
    tx.commit()
    vmctl.reload(sys)


def remove_vm_files(layout: Layout, name: str) -> None:
    validate_name(name)
    shutil.rmtree(layout.vm_dir(name))


def disk_problems(block: str, owner_uid: int) -> list[str]:
    f = confblock.facts(block)
    problems = []
    for path in [*f.disks, *([f.cdrom] if f.cdrom else [])]:
        try:
            st = os.lstat(path)
        except OSError as e:
            problems.append(f"{path}: {e.strerror}")
            continue
        if not stat.S_ISREG(st.st_mode):
            problems.append(f"{path}: not a regular file")
        elif st.st_uid not in (owner_uid, 0):
            problems.append(f"{path}: owned by uid {st.st_uid}")
    return problems


def _checked(sys: System, entry: VmEntry) -> None:
    if entry.conf_path is None:
        raise VmmError(f"VM '{entry.name}' is not managed by vmmanager")
    text = sys.read_file(entry.conf_path) or ""
    span = confblock.find_block(text, entry.name)
    if span is None:
        raise VmmError(f"No vm block for '{entry.name}' in {entry.conf_path}")
    try:
        uid = pwd.getpwnam(entry.owner).pw_uid
    except KeyError:
        raise VmmError(f"Unknown user '{entry.owner}'") from None
    problems = disk_problems(text[span[0]:span[1]], uid)
    if problems:
        raise VmmError(f"Refusing to start '{entry.name}': unsafe disk files", detail="\n".join(problems))


def start_vm(sys: System, layout: Layout, entry: VmEntry) -> None:
    _checked(sys, entry)
    vmctl.start(sys, entry.name)


def run_vm(sys: System, layout: Layout, entry: VmEntry) -> int:
    _checked(sys, entry)
    return vmctl.run_console(sys, entry.name)


def connect_vm(sys: System, entry: VmEntry) -> int:
    return vmctl.connect_console(sys, entry.name)


def stop_vm(sys: System, entry: VmEntry, force: bool = False) -> None:
    vmctl.stop(sys, entry.name, force)
